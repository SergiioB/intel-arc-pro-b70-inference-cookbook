#!/usr/bin/env python3
"""Generate scripts/INDEX.md: every script, its hash, and which ledger entries
and notes used it, so a script can be found from a result and vice versa.

Scripts are never moved (evidence cites their paths). Run after adding scripts:
    python3 tools/script_index.py
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
OUT = SCRIPTS / "INDEX.md"
CODE = {".py", ".sh", ".cpp", ".h", ".hpp", ".mjs", ".js", ".patch", ".sycl"}
SKIP_DIRS = {"__pycache__", "node_modules", ".mimosa", "evid", "debug", "vllm_src", "src_snapshot"}
DOC_ROOTS = ["research", "results", "decisions", "models", "engines", "campaigns", "docs"]
MAX_DOC = 2 * 1024 * 1024
NAME = re.compile(r"[\w.+-]+\.(?:py|sh|cpp|hpp|h|mjs|js|patch|sycl)\b")


def scripts():
    for p in sorted(SCRIPTS.rglob("*")):
        rel = p.relative_to(SCRIPTS)
        if not p.is_file() or p.suffix not in CODE or set(rel.parts[:-1]) & SKIP_DIRS:
            continue
        if len(rel.parts) > 4:  # vendored trees inside a campaign folder
            continue
        yield p


def corpus() -> dict[str, str]:
    docs = {}
    for root in DOC_ROOTS:
        for p in (ROOT / root).rglob("*"):
            if p.suffix in (".md", ".json", ".txt") and p.is_file() and p.stat().st_size < MAX_DOC:
                try:
                    docs[str(p.relative_to(ROOT))] = p.read_text(errors="replace")
                except OSError:
                    pass
    return docs


def mentions(texts: dict[str, str]) -> dict[str, set[str]]:
    """One pass: script basename -> keys of the texts that mention it."""
    out: dict[str, set[str]] = {}
    for key, text in texts.items():
        for name in set(NAME.findall(text)):
            out.setdefault(name, set()).add(key)
    return out


def main() -> int:
    ledger = json.loads((ROOT / "registry" / "research-ledger.json").read_text())["entries"]
    order = {e["id"]: i for i, e in enumerate(ledger)}
    led = mentions({e["id"]: json.dumps(e) for e in ledger})
    docs = mentions(corpus())
    rows = []
    for p in scripts():
        rel = str(p.relative_to(ROOT))
        rls = sorted(led.get(p.name, ()), key=order.get)
        cited = sorted(docs.get(p.name, ()))
        date = re.search(r"(20\d{6})", rel)
        when = (f"{date.group(1)[:4]}-{date.group(1)[4:6]}-{date.group(1)[6:]}" if date else
                time.strftime("%Y-%m-%d", time.localtime(p.stat().st_mtime)))
        sha = hashlib.sha256(p.read_bytes()).hexdigest()[:12]
        rows.append((when, rel, sha, rls, cited))
    rows.sort(key=lambda r: (r[0], r[1]), reverse=True)
    lines = [
        "<!-- GENERATED by tools/script_index.py - do not hand-edit -->", "",
        "# Script index", "",
        "Every script under `scripts/`, newest first, with the ledger entries and notes that cite it.",
        "Scripts are not moved because evidence cites their paths. `scripts/tmp/` is the",
        "experiment area (AGENTS.md section 14); promoted scripts live in `scripts/` or `tools/`.",
        "A script with no citation was never tied to a recorded result.", "",
        f"Scripts: {len(rows)}; cited by a ledger entry: {sum(1 for r in rows if r[3])}; "
        f"cited nowhere: {sum(1 for r in rows if not r[3] and not r[4])}.", "",
        "| date | script | sha256 | ledger | cited by (first 3 notes) |",
        "|---|---|---|---|---|",
    ]
    for when, rel, sha, rls, cited in rows:
        notes = "<br>".join(f"`{c}`" for c in cited[:3]) + (f" +{len(cited) - 3}" if len(cited) > 3 else "")
        lines.append(f"| {when} | `{rel}` | `{sha}` | {', '.join(rls) or '-'} | {notes or '-'} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} scripts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
